package compiler.compiler.binding.type

import compiler.binding.type.BoundIntersectionTypeReference
import compiler.binding.type.BoundTypeReference
import compiler.binding.type.NullableTypeReference
import compiler.binding.type.RootResolvedTypeReference
import compiler.compiler.negative.shouldHaveNoDiagnostics
import compiler.diagnostic.Diagnostic
import compiler.compiler.negative.validateModule
import io.kotest.core.spec.style.FreeSpec
import io.kotest.matchers.collections.shouldNotBeEmpty
import java.io.File

/**
 * Writes the emerge program `subtypinggrid` for the integration tests: it asks the runtime
 * (`emerge.core.reflection.isSubtypeOf`) whether each of the types of [TypeGrid] is below each, and prints
 * where the answer is not the one the frontend gives here. The program is a build product, not checked in;
 * `ProgramTests` of the integration tests runs it.
 *
 * Of [TypeGrid], it takes what the runtime can know and decide:
 * * no type parameters: the types of the grid are written within `Ctx`, the program has no values for its parameters
 * * no `own` types but `own Nothing`: `own` is no type argument, and `typeOf` takes the type as one
 * * no tokens and no `NonToken`: the runtime doesn't know what is a token
 * * only types that source code can name
 * * no intersections of disjoint classes, which the frontend takes for `Nothing`: the runtime doesn't know what is a class
 */
class RuntimeSubtypingGridTests : FreeSpec({
    "writes the program subtypinggrid" {
        val typeNames = TypeGrid.types
            .map { (name, _) -> name }
            .filter { name -> identifiersIn(name).none { it in TypeGrid.ctxParameters || it in TOKEN_RELATED } }
            .filter { name -> !OWN_BUT_NOTHING.containsMatchIn(name) }
            .distinct()
        val types = typeNames
            .map { it to TypeGrid.swCtx.parseType(it) }
            .filter { (_, type) -> !type.mentionsEffectivelyBottomIntersection() }
            // the grid has types that source code cannot name, e.g. `Box<A> & Box<C>`
            .filter { (name, _) -> isValidInSource(name) }
        types.shouldNotBeEmpty()

        val expectations = types.map { (_, subtype) ->
            types.map { (_, supertype) -> subtype.isSubtypeOf(supertype) }
        }

        val source = renderProgram(types.map { it.first }, expectations)
        // the frontend tests compile against the noop platform, which has all the program needs
        val sourceWithDeclarations = importsOf(source) + "\n" + TypeGrid.moduleSource + "\n\n" + withoutImports(source) + "\n"
        // warnings are fine: some types of the grid have no values, which is of no concern here
        validateModule(sourceWithDeclarations)
            .shouldHaveNoDiagnostics(allowedSeverities = Diagnostic.Severity.entries.filter { it < Diagnostic.Severity.ERROR }.toSet())

        val programDirectory = File("../integration-tests/target/generated-programs/$PROGRAM_NAME")
        programDirectory.deleteRecursively()
        File(programDirectory, "src").mkdirs()
        File(programDirectory, "src/main.em").writeText(
            "// Generated by frontend/src/test/kotlin/compiler/binding/type/RuntimeSubtypingGridTests.kt from TypeGrid; do not edit.\n" +
            "package $PROGRAM_NAME\n\n" + sourceWithDeclarations
        )
        File(programDirectory, "expected-stdout.txt").writeText(summaryLine(types.size) + "\n")
    }
})

private const val PROGRAM_NAME = "subtypinggrid"
private val OWN_BUT_NOTHING = Regex("""\bown\s+(?!Nothing\b)""")
private val IDENTIFIER = Regex("""[A-Za-z_][A-Za-z0-9_]*""")
private val TOKEN_RELATED = setOf("Tok", "Clk", "NonToken", "Shp", "Pl")

private fun identifiersIn(typeName: String): Sequence<String> = IDENTIFIER.findAll(typeName).map { it.value }

private fun summaryLine(nTypes: Int) = "compared each of $nTypes types with each"

private fun BoundTypeReference.mentionsEffectivelyBottomIntersection(): Boolean = when (this) {
    is BoundIntersectionTypeReference -> (isNonNullableNothing && components.none { it.isNonNullableNothing })
        || components.any { it.mentionsEffectivelyBottomIntersection() }
    is NullableTypeReference -> nested.mentionsEffectivelyBottomIntersection()
    is RootResolvedTypeReference -> arguments.orEmpty().any { it.type.mentionsEffectivelyBottomIntersection() }
    else -> false
}

/** only intersections can be invalid, of the types of the grid; the others are spared the check as it is slow */
private fun isValidInSource(typeName: String): Boolean {
    if ('&' !in typeName) {
        return true
    }

    val (_, diagnostics) = validateModule(
        "import emerge.core.reflection.typeOf\n" + TypeGrid.moduleSource + "\nfn probe() {\n    t = typeOf::<$typeName>()\n}\n"
    )
    return diagnostics.none { it.severity >= Diagnostic.Severity.ERROR }
}

private fun importsOf(source: String) = source.lineSequence().filter { it.startsWith("import ") }.joinToString("\n")
private fun withoutImports(source: String) = source.lineSequence().filter { !it.startsWith("import ") }.joinToString("\n").trim()

/**
 * @param expectations for each type, in the order of [typeNames], whether it is below each type
 * @return the functions of the program, with their imports; without a package declaration and the declarations of [TypeGrid]
 */
private fun renderProgram(typeNames: List<String>, expectations: List<List<Boolean>>): String = buildString {
    appendLine("import emerge.core.reflection.Type")
    appendLine("import emerge.core.reflection.typeOf")
    appendLine("import emerge.core.reflection.isSubtypeOf")
    appendLine("import emerge.platform.StandardOut")
    appendLine("import emerge.platform.World")
    appendLine()
    appendLine("fn gridTypes() -> Array<const Type> = [")
    appendLine(typeNames.joinToString(",\n") { "    typeOf::<$it>()" })
    appendLine("]")
    appendLine()
    appendLine("// for each of gridTypes(), whether the compiler takes it to be below each of gridTypes()")
    appendLine("fn gridExpectations() -> Array<Array<Bool>> = [")
    appendLine(expectations.joinToString(",\n") { row -> "    [" + row.joinToString(", ") + "]" })
    appendLine("]")
    appendLine()
    appendLine("""
        fn main(world: mut World) {
            stdout = StandardOut.take(world)!!
            types = gridTypes()
            expectations = gridExpectations()
            foreach subtypeIndex in 0..<types.size {
                foreach supertypeIndex in 0..<types.size {
                    subtype = types[subtypeIndex]
                    supertype = types[supertypeIndex]
                    expected = expectations[subtypeIndex][supertypeIndex]
                    if subtype.isSubtypeOf(supertype) != expected {
                        verdict = if expected "is" else "is not"
                        stdout.println(subtype.toString() + " " + verdict + " a subtype of " + supertype.toString() + " for the compiler, the runtime disagrees")
                    }
                }
            }
            stdout.println("${summaryLine(typeNames.size)}")
        }
    """.trimIndent())
}
